# Runs routes.sh generate: sets `status`, and leaves stdout and stderr in $work/out and $work/err
generate() { # <registry file, "" for registry.txt> <routes file> <app> <env>
  local registry=$1
  shift
  if [ -n "$registry" ]; then
    REGISTRY_FILE=$registry bash routes.sh generate "$@" > "$work/out" 2> "$work/err"
  else
    bash routes.sh generate "$@" > "$work/out" 2> "$work/err"
  fi
  status=$?
  cp "$work/out" "$work/all"
}

# 0013: $work/out becomes the site of <host>, out of the whole output ($work/all), which may hold an
# application's site and its MCP origin's
site() { # <host>
  awk -v opening="$1 {" '$0 == opening { on = 1 } on { print } on && $0 == "}" { exit }' "$work/all" > "$work/out"
  [ -s "$work/out" ] || { echo "no site $1 in:"; cat "$work/all"; return 1; }
}

exited() { # <status>
  [ "$status" -eq "$1" ] || { echo "exited $status, not $1; stderr:"; cat "$work/err"; return 1; }
}

exited_non_zero() {
  [ "$status" -ne 0 ] || { echo "exited 0; stdout:"; head -n 20 "$work/out"; return 1; }
}

says() { # <text>: stderr holds it
  grep -qF -- "$1" "$work/err" || { echo "stderr:"; cat "$work/err"; return 1; }
}

holds() { # <line, without its indentation>: the generated site holds it
  sed 's/^[[:space:]]*//' "$work/out" | grep -qxF -- "$1" || { echo "not in the site:"; cat "$work/out"; return 1; }
}

lacks() { # <text>: the generated site doesn't hold it
  ! grep -qF -- "$1" "$work/out" || { echo "in the site:"; grep -nF -- "$1" "$work/out"; return 1; }
}

# The body of the route's block `handle <matcher> {` (the catch-all for an empty matcher)
block() { # <matcher>
  local opening
  if [ -n "$1" ]; then opening="handle $1 {"; else opening="handle {"; fi
  awk -v opening="$opening" '
    { line = $0; sub(/^[ \t]+/, "", line) }
    !on && line == opening { on = 1; depth = 1; next }
    on {
      if (line ~ /\{$/) depth++
      if (line == "}") { depth--; if (depth == 0) exit }
      print line
    }' "$work/out"
}

block_holds() { # <matcher> <line>
  block "$1" | grep -qxF -- "$2" || { echo "handle $1 holds:"; block "$1"; return 1; }
}

block_lacks() { # <matcher> <text>
  ! block "$1" | grep -qF -- "$2" || { echo "handle $1 holds:"; block "$1"; return 1; }
}

# The routes' matchers, in the order of the site
handles() {
  sed -n 's/^[[:space:]]*handle \(.*\) {$/\1/p; s/^[[:space:]]*handle {$/(any)/p' "$work/out" | paste -sd' ' -
}

handles_are() { # <matchers…>
  [ "$(handles)" = "$*" ] || { echo "handles: $(handles)"; return 1; }
}

# A dev HTTPS upstream: verified against the local CA, with the client's Host
https_upstream() { # <matcher> <url>
  block_holds "$1" "reverse_proxy $2 {"
  block_holds "$1" 'header_up Host {hostport}'
  block_holds "$1" 'tls_server_name host.docker.internal'
  block_holds "$1" 'tls_trust_pool file /certs/ca.crt'
}

spa() { # <matcher> <upstream>: a front end, with the single-page-app headers
  block_holds "$1" 'import spa-headers'
  block_holds "$1" "reverse_proxy $2"
}

refused() { # <fixture> <line> <text>
  generate "$FIXTURES/registry.txt" "$FIXTURES/refused-$1.routes" faito dev
  check "refused $1: exits 1" exited 1
  check "refused $1: names the file and line $2" says "refused-$1.routes:$2: "
  check "refused $1: says \"$3\"" says "$3"
  check "refused $1: prints no site" test ! -s "$work/out"
}

