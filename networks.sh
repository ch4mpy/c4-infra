#!/usr/bin/env bash
# Each application's own network (intent 0007): its containers join c4-infra.<app> as an external
# network, which no other application's container joins, and the shared services it uses are
# attached to it, by their service names. Keycloak's database is on none of them (it is on
# c4-infra.keycloak-db, Keycloak's only), and c4-infra holds the shared services only.
#
#   networks.sh ensure <app>     creates c4-infra.<app>, labelled c4-infra.app=<app>, when it is
#                                missing (<app> from the registry, registry.txt), attaches each running
#                                shared service but keycloak-db that isn't on it yet, under its
#                                service name (and the reverse proxy under the shared host's name too,
#                                INFRA_HOST, on the demo host: the applications reach the issuer
#                                through it), then writes compose.apps.yml. register-app.sh runs it
#                                at every registration, demo/c4-app before `up`.
#   networks.sh compose-file     writes compose.apps.yml, the last file of COMPOSE_FILE (.env): each
#                                shared service but keycloak-db joins each network labelled
#                                c4-infra.app (external), the reverse proxy under INFRA_HOST too on the
#                                demo host, so that the attachments survive the stack's recreation
#                                (up.sh, demo/deploy.sh and the workflow run it before compose).
#                                Rewritten only when the Docker daemon answers (its version), one
#                                rewrite at a time (flock on this directory, where flock exists: not
#                                in Git Bash); otherwise created as "services: {}" when missing, and
#                                left as it is.
#   networks.sh remove <app>     detaches the shared services from c4-infra.<app> and removes it, then
#                                writes compose.apps.yml (the tests' cleanup of their fixtures)
#
# Run as root (demo/c4-app), what it writes gets the stack directory's owner, as register-app.sh's.
set -euo pipefail
# Git Bash would rewrite the --format templates' paths, if any; the container names have none
export MSYS_NO_PATHCONV=1

INFRA_DIR=$(cd "$(dirname "$0")" && pwd)
APPS_FILE=$INFRA_DIR/compose.apps.yml
# the shared services attached to each application's network: everything of the stack but
# keycloak-db (compose.yml)
SHARED=(reverse-proxy keycloak mailpit rabbitmq grafana-lgtm)

# shellcheck source=registry.sh
source "$INFRA_DIR/registry.sh"

own() { # <path>
  [ "$(id -u)" -eq 0 ] || return 0
  chown --reference="$INFRA_DIR" "$1"
}

valid_name() { # <app>: an application's name (registry.txt's rule)
  [[ $1 =~ ^[a-z][a-z0-9-]*$ ]] || { echo "networks.sh: '$1' is not an application's name" >&2; return 1; }
}

# The applications' networks: those labelled c4-infra.app=<app> and named c4-infra.<app>, sorted
app_networks() {
  local name app
  docker network ls --filter label=c4-infra.app --format '{{.Name}} {{.Label "c4-infra.app"}}' | tr -d '\r' \
    | while read -r name app; do
        if [[ $app =~ ^[a-z][a-z0-9-]*$ ]] && [ "$name" = "c4-infra.$app" ]; then
          echo "$name"
        fi
      done | sort
}

compose_file() {
  local networks network service demo=false next infra_env
  # a fake docker (the tests' stubs) or a stopped daemon answers nothing: never empty the file then
  if [ -z "$(docker info --format '{{.ServerVersion}}' 2> /dev/null | tr -d '\r')" ]; then
    if [ ! -f "$APPS_FILE" ]; then
      printf 'services: {}\n' > "$APPS_FILE"
      own "$APPS_FILE"
    fi
    return 0
  fi
  # before the file is touched: a refused INFRA_ENV must not drop the INFRA_HOST alias
  stack_env_read infra_env INFRA_ENV
  [ "$infra_env" != demo ] || demo=true
  # one rewrite at a time, whichever account runs it (c4-app's own lock is per application)
  if command -v flock > /dev/null; then
    exec 8< "$INFRA_DIR"
    flock 8
  fi
  networks=$(app_networks)
  # a name of its own, next to the file (the rename stays on one file system)
  next=$(mktemp "$APPS_FILE.XXXXXX")
  chmod 0644 "$next"
  {
    echo "# Generated by networks.sh compose-file (intent 0007), from the networks labelled c4-infra.app:"
    echo "# don't edit. Each shared service but keycloak-db joins each application's network."
    if [ -z "$networks" ]; then
      echo 'services: {}'
    else
      echo 'services:'
      for service in "${SHARED[@]}"; do
        echo "  $service:"
        echo "    networks:"
        for network in $networks; do
          if [ "$service" = reverse-proxy ] && $demo; then
            echo "      $network:"
            echo "        aliases: ['\${INFRA_HOST}']"
          else
            echo "      $network: {}"
          fi
        done
      done
      echo 'networks:'
      for network in $networks; do
        echo "  $network:"
        echo "    name: $network"
        echo "    external: true"
      done
    fi
  } > "$next"
  # in one step: a compose reading it never sees half a file
  mv -f "$next" "$APPS_FILE"
  own "$APPS_FILE"
  exec 8<&-
}

ensure() { # <app>
  local app=$1 network=c4-infra.$1 service container aliases host infra_env
  valid_name "$app" || return 1
  # named from the registry only (intent 0004 reserves the shared services' names)
  registry_entry "$app" > /dev/null || return 1
  # before any change: a refused value stops here, with no network created nor attached
  stack_env_read host INFRA_HOST
  stack_env_read infra_env INFRA_ENV
  if ! docker network inspect "$network" > /dev/null 2>&1; then
    docker network create --label "c4-infra.app=$app" "$network" > /dev/null
    echo "Network $network created"
  fi
  for service in "${SHARED[@]}"; do
    container=c4-infra.$service
    [ "$(docker inspect -f '{{.State.Running}}' "$container" 2> /dev/null | tr -d '\r')" = true ] || continue
    if docker inspect -f '{{range $name, $_ := .NetworkSettings.Networks}}{{$name}}{{"\n"}}{{end}}' "$container" \
      | tr -d '\r' | grep -qxF "$network"; then
      continue
    fi
    aliases=(--alias "$service")
    if [ "$service" = reverse-proxy ] && [ "$infra_env" = demo ] && [ -n "$host" ]; then
      aliases+=(--alias "$host")
    fi
    docker network connect "${aliases[@]}" "$network" "$container"
    echo "Network $network: $service attached"
  done
  compose_file
}

remove() { # <app>
  local app=$1 network=c4-infra.$1 service
  valid_name "$app" || return 1
  if [ "$(docker network inspect -f '{{index .Labels "c4-infra.app"}}' "$network" 2> /dev/null | tr -d '\r')" = "$app" ]; then
    for service in "${SHARED[@]}"; do
      docker network disconnect -f "$network" "c4-infra.$service" > /dev/null 2>&1 || true
    done
    docker network rm "$network" > /dev/null
    echo "Network $network removed"
  fi
  compose_file
}

case "${1:-}" in
  ensure)
    [ $# -eq 2 ] || { echo "Usage: $0 ensure <app>" >&2; exit 2; }
    ensure "$2"
    ;;
  compose-file)
    [ $# -eq 1 ] || { echo "Usage: $0 compose-file" >&2; exit 2; }
    compose_file
    ;;
  remove)
    [ $# -eq 2 ] || { echo "Usage: $0 remove <app>" >&2; exit 2; }
    remove "$2"
    ;;
  *)
    echo "Usage: $0 ensure <app> | compose-file | remove <app>" >&2
    exit 2
    ;;
esac
